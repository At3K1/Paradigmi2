/**
 * Базовый интерфейс «Элемент».
 * Любой элемент напитка (ингредиент или действие) реализует этот контракт.
 */
export interface Element {
  /** Человекочитаемое название элемента (например, «Вода», «Перемешать»). */
  readonly name: string;

  /** Текстовое описание элемента — используется при выводе рецепта. */
  describe(): string;
}
